// KilometersMiles class to convert kilometers into miles

class KilometersMiles{
	public static void main(String[] args){
		
		// Variable to indicate kilometers value
		float kilometers = 10.8f;
		
		// Variable to indicate miles value
		float miles = kilometers / 1.6f;
		
		// Print value in miles
		System.out.println("The distance " + kilometers + " km in miles is " + miles);
	}
}